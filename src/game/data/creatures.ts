export type Rarity = 'common' | 'uncommon' | 'rare' | 'legendary'
export type BiomeId = 'forest' | 'canyon'

/** Shape archetypes for the procedural placeholder models. */
export type PlaceholderShape = 'quadruped' | 'bird' | 'tortoise' | 'lizard' | 'serpent'

export interface PlaceholderStyle {
  shape: PlaceholderShape
  /** Overall body length in metres. */
  size: number
  body: string
  accent: string
  /** Optional extra colour: legs/nose, or the glow on legendaries. */
  detail?: string
  /** Leg colour when it differs from `detail`. */
  legs?: string
  ears?: 'pointed' | 'huge' | 'round' | 'none'
  tail?: 'bushy' | 'short' | 'long' | 'none'
  antlers?: boolean
  glow?: boolean
  translucent?: boolean
}

export interface CreatureDef {
  id: string
  name: string
  biome: BiomeId
  rarity: Rarity
  /** Exhibit income in $/min. */
  income: number
  description: string
  /** Generated by scripts/generate_assets; falls back to the placeholder when missing. */
  asset: string
  icon: string
  placeholder: PlaceholderStyle
  /** Procedural call used for sound cues. */
  call: CallKind
  /** Visible height of the model in metres, used to scale generated GLBs. */
  height: number
  /** Flying creatures must live in a roofed aviary at the zoo. */
  flies?: boolean
}

export type CallKind = 'yip' | 'grunt' | 'hoot' | 'bell' | 'chirp' | 'hiss' | 'rasp' | 'chime'

export const INCOME_BY_RARITY: Record<Rarity, number> = {
  common: 2,
  uncommon: 5,
  rare: 12,
  legendary: 40,
}

const def = (c: Omit<CreatureDef, 'income' | 'asset' | 'icon'>): CreatureDef => ({
  ...c,
  income: INCOME_BY_RARITY[c.rarity],
  asset: `assets/creatures/${c.id}.glb`,
  icon: `assets/creatures/${c.id}.png`,
})

