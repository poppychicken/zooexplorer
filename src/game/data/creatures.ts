export interface CreatureDef {
  id: string
  name: string
  biome: BiomeId
  rarity: Rarity
  /** Added to the ticket price for every one of these animals in the zoo, in $. */
  ticket: number
  /** What each of these animals earns in $/min: its ticket share × visitors per minute. */
  income: number
  description: string
  /** Generated by scripts/generate_assets; falls back to the placeholder when missing. */
  asset: string
  icon: string
  placeholder: PlaceholderStyle
  /** Procedural call used for sound cues. */
  call: CallKind
  /** Visible height of the model in metres, used to scale generated GLBs. */
  height: number
  /** Flying creatures must live in a roofed aviary at the zoo. */
  flies?: boolean
}

export type CallKind = 'yip' | 'grunt' | 'hoot' | 'bell' | 'chirp' | 'hiss' | 'rasp' | 'chime' | 'thump' | 'snuffle' | 'whistle' | 'bleat' | 'growl' | 'bray' | 'bark' | 'song'

/** How much each animal of this rarity adds to the zoo's ticket price, in $. */
export const TICKET_BY_RARITY: Record<Rarity, number> = {
  common: 0.5,
  uncommon: 1.25,
  rare: 3,
  legendary: 10,
}

/** Visitors arriving per minute once the zoo has at least one animal. */
export const VISITORS_PER_MINUTE = 4

const def = (c: Omit<CreatureDef, 'ticket' | 'income' | 'asset' | 'icon'>): CreatureDef => ({
  ...c,
  ticket: TICKET_BY_RARITY[c.rarity],
  income: TICKET_BY_RARITY[c.rarity] * VISITORS_PER_MINUTE,
  asset: `assets/creatures/${c.id}.glb`,
  icon: `assets/creatures/${c.id}.png`,
})

